export function generationPrompt(phase, requestedLevels) {
  const stage = phase === 'converge' ? CONVERGENCE_PROMPT : EXPLORATION_PROMPT;
  return `${SHARED_PROMPT}\n\n${stage}\n\n【本批边界】本次最多生成 ${requestedLevels} 层。到达这一层只表示本批停止；尚未稳定的末端节点须保持 terminal=false、children=[]，并用 memory 记录已发生的变化和待定问题，以便下一批从这里继续。不要把本批层数当成整个故事的结局深度。`;
}

